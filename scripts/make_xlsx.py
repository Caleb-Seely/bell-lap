"""Write the question bank as a review workbook: data/photo-finish-bank.xlsx (needs openpyxl)"""
import json, csv, os
from openpyxl import Workbook
from openpyxl.styles import Font, PatternFill, Alignment
from openpyxl.utils import get_column_letter

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
HERE = os.path.join(ROOT, "data")
qs = json.load(open(os.path.join(HERE, "questions.json")))
hist = json.load(open(os.path.join(HERE, "wr_history.json")))
review = list(csv.DictReader(open(os.path.join(HERE, "review.csv"))))

def mk(v, fmt):
    if fmt == "m": return f"{v:.2f}"
    if fmt == "s": return f"{v:.2f}"
    if fmt == "ms":
        m = int(v // 60); return f"{m}:{v - m*60:05.2f}"
    h = int(v // 3600); m = int((v - h*3600) // 60); s = round(v - h*3600 - m*60)
    return f"{h}:{m:02d}:{s:02d}"

F = "Arial"
head = Font(name=F, bold=True, color="FFFFFF"); headfill = PatternFill("solid", fgColor="15171C")
body = Font(name=F); bold = Font(name=F, bold=True)
editfill = PatternFill("solid", fgColor="FFF2CC")
flagfont = Font(name=F, color="C8442C")

wb = Workbook()
def sheet(title, headers, widths):
    ws = wb.create_sheet(title)
    ws.append(headers)
    for i, w in enumerate(widths, 1):
        ws.column_dimensions[get_column_letter(i)].width = w
        c = ws.cell(row=1, column=i); c.font = head; c.fill = headfill; c.alignment = Alignment(vertical="center")
    ws.freeze_panes = "A2"
    return ws

# README
ws = wb.active; ws.title = "Read me"
lines = [
    ("Photo Finish question bank", bold),
    ("Every individual final at the Olympic Games and outdoor World Athletics Championships, 2016 to 2025 (8 championships, 38 events each, 304 finals).", body),
    ("Relays, race walks and combined events are left out. Source: the final results table on each event's Wikipedia page, collected October 2026.", body),
    ("", body),
    ("Tabs", bold),
    ("Finals: one row per question. The game's answer is the winning mark; the clue is the row named in 'Clue athlete'.", body),
    ("Results: every finisher with a valid mark. Marathons and 10,000 m races with more than 20 finishers list places 1-10 plus the last finisher.", body),
    ("World records: the record going into each championship, plus the records set in these finals.", body),
    ("Review: items a person should check before a question goes live (injured last-place runners, short fields, ties, unclear marks).", body),
    ("", body),
    ("What to edit", bold),
    ("Yellow cells in the Finals tab ('Verified' and 'Editor note') are for you. Mark Verified = Y once you have checked the final against World Athletics results.", body),
    ("Example: 2024-OG-M100 | Verified: Y | Editor note: Lyles 9.784 vs Thompson 9.789, both shown as 9.79.", body),
    ("Everything else is generated by build.py from the raw files; change the raw files and rebuild rather than editing those cells.", body),
]
for t, f in lines:
    ws.append([t]); ws.cell(row=ws.max_row, column=1).font = f
ws.column_dimensions["A"].width = 130

fin = sheet("Finals", ["ID", "Championship", "City", "Year", "Gender", "Event", "Group", "Winner", "Country", "Winning mark",
                       "Clue athlete", "Clue place", "Clue mark", "Finishers listed", "Field size", "WR going in", "WR holder", "WR year",
                       "World record set", "Review flags", "Verified", "Editor note"],
            [18, 20, 15, 7, 8, 20, 10, 26, 8, 12, 26, 9, 11, 9, 9, 11, 26, 8, 9, 26, 9, 40])
res = sheet("Results", ["Final ID", "Place", "Athlete", "Country", "Mark", "Value (s or m)"], [18, 7, 30, 8, 11, 13])
for q in qs:
    r = q["results"]; c = r[q["clue_index"]]; w = q["wr_before"] or {}
    fin.append([q["id"], q["championship"], q["city"], q["year"], q["gender"], q["label"].split("'s ", 1)[1], q["group"],
                r[0][1], r[0][2], q["answer_mark"], c[1], c[0], mk(c[3], q["fmt"]), None, r[-1][0],
                w.get("mark"), w.get("holder"), w.get("year"), "Y" if q["wr_broken"] else "",
                ", ".join(f for f in q["flags"]), "", ""])
    row = fin.max_row
    fin.cell(row=row, column=14).value = f'=COUNTIF(Results!$A:$A,A{row})'
    for col in (21, 22): fin.cell(row=row, column=col).fill = editfill
    for x in r:
        res.append([q["id"], x[0], x[1], x[2], mk(x[3], q["fmt"]), round(x[3], 2)])
for wsx in (fin, res):
    for row in wsx.iter_rows(min_row=2):
        for c in row: c.font = body
for row in fin.iter_rows(min_row=2):
    if row[19].value: row[19].font = flagfont
fin.auto_filter.ref = fin.dimensions; res.auto_filter.ref = res.dimensions

wr = sheet("World records", ["Event", "Mark", "Holder", "Year", "Going into", "Set in final"], [22, 11, 28, 7, 60, 18])
for key, h in hist.items():
    for rec in h["records"]:
        wr.append([h["label"], rec["mark"], rec["holder"], rec["year"], ", ".join(rec["seen_before"]), rec.get("set_in", "")])
for row in wr.iter_rows(min_row=2):
    for c in row: c.font = body
wr.auto_filter.ref = wr.dimensions

rv = sheet("Review", ["Final ID", "Issue", "Note", "Resolved"], [18, 14, 90, 10])
for item in review:
    rv.append([item["id"], item["issue"], item["note"], ""])
    rv.cell(row=rv.max_row, column=4).fill = editfill
for row in rv.iter_rows(min_row=2):
    for c in row[:3]: c.font = body
rv.auto_filter.ref = rv.dimensions

wb.save(os.path.join(HERE, "photo-finish-bank.xlsx"))
print("saved")
